/// Italian when the OS display language is Italian, English otherwise.
pub fn for_system() -> &'static Strings {
    let locale = sys_locale::get_locale().unwrap_or_default().to_lowercase();
    if locale.starts_with("it") {
        &ITALIAN
    } else {
        &ENGLISH
    }
}
